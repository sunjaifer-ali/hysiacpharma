function buildInvoice(opts: {
  n: number;
  date: string;
  party: Party;
  status: Invoice["status"];
  paidRatio?: number;
  items: { product: Product; qty: number; discount?: number; freeQty?: number }[];
  notes?: string;
}): Invoice {
  const intra = isIntraState(DEFAULT_COMPANY.stateCode, opts.party.stateCode);
  const priceList = priceListForChannel(opts.party.channel);
  const lines = opts.items.map((it, idx) =>
    lineFrom(it.product, it.qty, intra, {
      discount: it.discount,
      freeQty: it.freeQty,
      priceList,
      id: `inv-${opts.n}-l-${idx}`,
    }),
  );
  const taxable = lines.reduce((s, l) => s + l.taxable, 0);
  const tax = lines.reduce((s, l) => s + l.cgst + l.sgst + l.igst, 0);
  const grand = Math.round((taxable + tax) * 100) / 100;
  const paid =
    opts.status === "paid"
      ? grand
      : opts.status === "partial"
        ? Math.round(grand * (opts.paidRatio ?? 0.5) * 100) / 100
        : 0;
  return {
    id: `inv-${opts.n}`,
    number: formatInvoiceNumber(DEFAULT_COMPANY.invoicePrefix, opts.n),
    date: opts.date,
    status: opts.status,
    partyId: opts.party.id,
    party: partySnap(opts.party),
    company: snapshotCompany(DEFAULT_COMPANY),
    placeOfSupply: opts.party.stateCode,
    reverseCharge: false,
    priceList,
    lines,
    roundOff: 0,
    notes: opts.notes ?? "",
    paidAmount: paid,
    salesman: DEFAULT_COMPANY.salesman,
    poNumber: "",
    billKind: opts.party.channel === "walkin" ? "cash" : "credit",
    transport: "",
    ewayBill: "",
    transportCharges: 0,
    otherCharges: 0,
    creditApplied: 0,
    createdAt: `${opts.date}T10:00:00.000Z`,
    updatedAt: `${opts.date}T10:00:00.000Z`,
  };
}

