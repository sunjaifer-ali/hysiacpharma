function purchaseLine(
  product: Product,
  qty: number,
  intra: boolean,
  id: string,
  purchaseRate: number,
  extra?: Partial<PurchaseLine>,
): PurchaseLine {
  const tax = calcLine({
    qty,
    rate: purchaseRate,
    discount: extra?.discount ?? 0,
    gstRate: extra?.gstRate ?? product.gstRate,
    intraState: intra,
  });
  return {
    id,
    productId: product.id,
    name: extra?.name ?? `${product.name} (${product.genericName})`,
    hsn: extra?.hsn ?? product.hsn,
    pack: extra?.pack ?? product.pack,
    unit: extra?.unit ?? product.unit,
    manufacturer: extra?.manufacturer ?? product.manufacturer,
    batch: extra?.batch ?? product.batch,
    expiry: extra?.expiry ?? product.expiry,
    mfgDate: extra?.mfgDate ?? "",
    qty,
    freeQty: extra?.freeQty ?? 0,
    mrp: extra?.mrp ?? product.mrp,
    ptsPercent: product.ptsPercent,
    ptrPercent: product.ptrPercent,
    pts: product.pts,
    ptr: product.ptr,
    purchaseRate,
    discount: extra?.discount ?? 0,
    gstRate: extra?.gstRate ?? product.gstRate,
    ...tax,
  };
}

