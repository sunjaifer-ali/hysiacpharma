function withTrade(
  p: Omit<Product, "pts" | "ptr" | "ptsPercent" | "ptrPercent" | "itemId"> & { itemId?: string },
): Product {
  const pts = p.rate;
  const ptsPercent = pctOf(pts, p.mrp);
  const ptrPercent = derivePtrPercent(ptsPercent);
  const ptr = fromPct(p.mrp, ptrPercent);
  return { ...p, itemId: p.itemId ?? p.id, pts, ptr, ptsPercent, ptrPercent };
}

