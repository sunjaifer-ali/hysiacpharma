function lineFrom(
  product: Product,
  qty: number,
  intra: boolean,
  extras?: Partial<Pick<InvoiceLine, "discount" | "freeQty" | "rate" | "priceList">> & { id: string },
): InvoiceLine {
  const priceList = extras?.priceList ?? "pts";
  const rate = extras?.rate ?? (priceList === "ptr" ? product.ptr : product.pts);
  const discount = extras?.discount ?? 0;
  const tax = calcLine({ qty, rate, discount, gstRate: product.gstRate, intraState: intra });
  return {
    id: extras?.id ?? `${product.id}-${qty}`,
    productId: product.id,
    name: `${product.name} (${product.genericName})`,
    hsn: product.hsn,
    pack: product.pack,
    unit: product.unit,
    manufacturer: product.manufacturer,
    batch: product.batch,
    expiry: product.expiry,
    qty,
    freeQty: extras?.freeQty ?? 0,
    mrp: product.mrp,
    pts: product.pts,
    ptr: product.ptr,
    ptsPercent: product.ptsPercent,
    ptrPercent: product.ptrPercent,
    priceList,
    rate,
    discount,
    gstRate: product.gstRate,
    ...tax,
  };
}

